import { fireEvent, render, screen, within } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import { expect, it } from 'vitest'
import App from './App'

it('composes two named experiments with native anchors and one page heading', () => {
  const { container } = render(<App />)
  expect(screen.getAllByRole('heading', { level: 1 })).toHaveLength(1)
  expect(screen.getByRole('heading', { level: 1 })).toHaveTextContent('Explore optical illusions')
  expect(screen.getAllByRole('heading', { level: 2 }).map((heading) => heading.textContent)).toEqual(['Confetti illusion', 'Munker illusion'])
  const navigation = screen.getByRole('navigation', { name: 'Illusions' })
  for (const [name, id] of [['Confetti', 'confetti'], ['Munker', 'munker']]) {
    expect(within(navigation).getByRole('link', { name })).toHaveAttribute('href', '#' + id)
    expect(document.getElementById(id)).toContainElement(screen.getByRole('article', { name: name + ' illusion' }))
  }
  expect(screen.getByRole('link', { name: 'OpticEye' })).toHaveAttribute('href', import.meta.env.BASE_URL)
  const ids = Array.from(container.querySelectorAll('[id]')).map((element) => element.id)
  expect(new Set(ids).size).toBe(ids.length)
})

it('preserves independent circle, oranges and Munker settings across navigation and each reset', async () => {
  const user = userEvent.setup()
  render(<App />)
  const confetti = within(screen.getByRole('article', { name: 'Confetti illusion' }))
  const munker = within(screen.getByRole('article', { name: 'Munker illusion' }))
  const circles = confetti.getByRole('button', { name: 'Show base colors' })
  const net = confetti.getByRole('button', { name: 'Hide netting' })
  const bars = munker.getByRole('button', { name: 'Show base color' })
  await user.click(circles)
  await user.click(net)
  await user.selectOptions(confetti.getByRole('combobox', { name: 'Image source' }), 'ai')
  await user.selectOptions(confetti.getByRole('combobox', { name: 'Image size' }), '240')
  await user.selectOptions(confetti.getByRole('combobox', { name: 'Oranges image size' }), '720')
  fireEvent.change(confetti.getByRole('slider'), { target: { value: '8' } })
  await user.click(screen.getByRole('link', { name: 'Munker' }))
  expect(circles).toHaveAttribute('aria-pressed', 'true')
  await user.click(bars)
  await user.selectOptions(munker.getByRole('combobox'), '720')
  fireEvent.change(munker.getByRole('slider'), { target: { value: '12' } })
  await user.click(munker.getByRole('button', { name: 'Reset Munker' }))
  expect(circles).toHaveAttribute('aria-pressed', 'true')
  expect(net).toHaveAttribute('aria-pressed', 'true')
  expect(confetti.getByRole('slider')).toHaveValue('8')
  expect(confetti.getByRole('combobox', { name: 'Image size' })).toHaveValue('240')
  expect(confetti.getByRole('combobox', { name: 'Image source' })).toHaveValue('ai')
  expect(confetti.getByRole('combobox', { name: 'Oranges image size' })).toHaveValue('720')
  await user.click(bars)
  fireEvent.change(munker.getByRole('slider'), { target: { value: '3' } })
  await user.selectOptions(munker.getByRole('combobox'), '240')
  await user.click(screen.getByRole('link', { name: 'Confetti' }))
  await user.click(confetti.getByRole('button', { name: 'Reset' }))
  expect(bars).toHaveAttribute('aria-pressed', 'true')
  expect(munker.getByRole('slider')).toHaveValue('3')
  expect(munker.getByRole('combobox')).toHaveValue('240')
  expect(circles).toHaveAttribute('aria-pressed', 'false')
  expect(net).toHaveAttribute('aria-pressed', 'false')
  expect(confetti.getByRole('combobox', { name: 'Image source' })).toHaveValue('illustration')
})
